import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { TRACKS, TRACK_IDS, generateRound, parseNumber } from "./index";

const FILE = path.resolve(__dirname, "../../../../content/drill-test-vectors.json");
const SEEDS = [1, 2, 3, 42, 12345, 987654321];

function build() {
  const rounds = TRACK_IDS.flatMap((track) =>
    Array.from({ length: TRACKS[track].maxLevel }, (_, i) => i + 1).flatMap((level) =>
      SEEDS.map((seed) => ({ track, level, seed, problems: generateRound({ track, level, seed }).map((p) => ({ prompt: p.prompt, answer: p.answer, ...(p.choices ? { choices: p.choices } : {}) })) })),
    ),
  );
  const numbers = ["1,200", "1.5k", "3m", "2e6", "1.2 million", "abc", "", "  42 ", "-7", "0.5", "2b"].map((input) => ({ input, value: parseNumber(input) ?? null }));
  return {
    note: "Generated by web/src/lib/drills/drillVectors.test.ts (UPDATE_VECTORS=1 to regenerate). The Swift drills must reproduce every round exactly.",
    rounds,
    numbers,
  };
}

describe("drill test vectors (shared with the iOS app)", () => {
  it("match content/drill-test-vectors.json", () => {
    const fresh = build();
    if (process.env.UPDATE_VECTORS) {
      writeFileSync(FILE, JSON.stringify(fresh, null, 2) + "\n");
      return;
    }
    expect(JSON.parse(readFileSync(FILE, "utf8"))).toEqual(JSON.parse(JSON.stringify(fresh)));
  });
});
