import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { Rating, applyReview, FAST_MS, FSRS_PARAMS, newReview, ratingFor, tomorrowStart, type ReviewRow } from "./fsrs";

const VECTORS = path.resolve(__dirname, "../../../content/fsrs-test-vectors.json");
const START = new Date("2026-01-05T09:00:00Z").getTime();
const DAY = 86_400_000;

describe("automatic rating", () => {
  it("wrong = Again whatever the speed", () => {
    for (const kind of Object.keys(FAST_MS) as (keyof typeof FAST_MS)[]) {
      expect(ratingFor(kind, false, 100)).toBe(Rating.Again);
      expect(ratingFor(kind, false, 60_000)).toBe(Rating.Again);
    }
  });
  it("right + fast = Easy, right + slow = Good, per kind", () => {
    for (const [kind, limit] of Object.entries(FAST_MS) as [keyof typeof FAST_MS, number][]) {
      expect(ratingFor(kind, true, limit)).toBe(Rating.Easy);
      expect(ratingFor(kind, true, limit + 1)).toBe(Rating.Good);
    }
  });
  it("true/false has a tighter fast threshold than cloze", () => {
    expect(FAST_MS.tf).toBeLessThan(FAST_MS.mcq);
    expect(FAST_MS.mcq).toBeLessThan(FAST_MS.cloze);
  });
});

describe("scheduling", () => {
  it("first check is tomorrow, not minutes away", () => {
    const row = newReview("p", "c", START);
    expect(row.state).toBe(0);
    expect(row.due_at).toBeGreaterThan(START + 6 * 3_600_000);
    expect(row.due_at).toBeLessThanOrEqual(START + 2 * DAY);
    expect(new Date(row.due_at).getHours()).toBe(0);
    expect(tomorrowStart(row.due_at - 1)).toBeGreaterThan(row.due_at - 1);
  });
  it("remembering pushes the next check further out each time", () => {
    let row = newReview("p", "c", START);
    let at = row.due_at;
    let last = 0;
    for (let i = 0; i < 4; i++) {
      row = applyReview(row, Rating.Good, at);
      const gap = row.due_at - at;
      expect(gap).toBeGreaterThan(last);
      last = gap;
      at = row.due_at;
    }
  });
  it("forgetting brings it back sooner and counts a lapse", () => {
    let row = newReview("p", "c", START);
    let at = row.due_at;
    for (let i = 0; i < 3; i++) {
      row = applyReview(row, Rating.Good, at);
      at = row.due_at;
    }
    const before = row.due_at - row.last_review_at!;
    const lapsed = applyReview(row, Rating.Again, at);
    expect(lapsed.lapses).toBe(1);
    expect(lapsed.due_at - at).toBeLessThan(before);
    expect(lapsed.stability).toBeLessThan(row.stability);
  });
});

// ---------- cross-platform test vectors (for the Swift port) ----------

type Step = { rating: 1 | 2 | 3 | 4; wait: "due" | number };
const CASES: { name: string; steps: Step[] }[] = [
  { name: "good-streak", steps: Array(6).fill({ rating: 3, wait: "due" }) },
  { name: "easy-start", steps: [{ rating: 4, wait: "due" }, { rating: 4, wait: "due" }, { rating: 3, wait: "due" }] },
  { name: "again-then-recover", steps: [{ rating: 1, wait: "due" }, { rating: 3, wait: "due" }, { rating: 3, wait: "due" }, { rating: 2, wait: "due" }] },
  { name: "lapse-after-streak", steps: [{ rating: 3, wait: "due" }, { rating: 3, wait: "due" }, { rating: 3, wait: "due" }, { rating: 1, wait: "due" }, { rating: 3, wait: "due" }] },
  { name: "late-reviews", steps: [{ rating: 3, wait: 2 }, { rating: 3, wait: 30 }, { rating: 4, wait: 90 }] },
  { name: "early-review", steps: [{ rating: 3, wait: "due" }, { rating: 3, wait: 1 }, { rating: 3, wait: "due" }] },
];

function runCase(steps: Step[]) {
  let row: ReviewRow = newReview("vector-probe", "vector-card", START);
  const first = row.due_at;
  let at = row.due_at;
  const out = [];
  for (const s of steps) {
    if (s.wait !== "due") at = (out.length ? at : START) + s.wait * DAY;
    // for the very first step a numeric wait is measured from the initial due time
    if (s.wait !== "due" && out.length === 0) at = row.due_at + (s.wait - 1) * DAY;
    row = applyReview(row, s.rating, at);
    out.push({
      rating: s.rating,
      // Offsets keep the vectors independent of the machine timezone (only the first due time depends on it).
      at_offset_ms: at - first,
      interval_ms: row.due_at - at,
      stability: row.stability,
      difficulty: row.difficulty,
      scheduled_days: row.scheduled_days,
      elapsed_days: row.elapsed_days,
      reps: row.reps,
      lapses: row.lapses,
      state: row.state,
    });
    at = row.due_at;
  }
  return out;
}

function buildVectors() {
  return {
    note: "Generated by web/src/lib/fsrs.test.ts (UPDATE_VECTORS=1 to regenerate). The Swift port must reproduce `expected` for every step, with tolerance 1e-6 on stability/difficulty and exact ms on due_at.",
    parameters: FSRS_PARAMS,
    initial: { note: "The first review is due at the start of the next local day (at least 6 h away). Step times are given as offsets from that first due time: at_offset_ms = review time - first due time; interval_ms = next due - review time." },
    cases: CASES.map((c) => ({ name: c.name, steps: c.steps, expected: runCase(c.steps) })),
  };
}

describe("fsrs test vectors", () => {
  it("match content/fsrs-test-vectors.json", () => {
    const fresh = buildVectors();
    if (process.env.UPDATE_VECTORS) {
      writeFileSync(VECTORS, JSON.stringify(fresh, null, 2) + "\n");
      return;
    }
    const saved = JSON.parse(readFileSync(VECTORS, "utf8"));
    expect(saved.parameters).toEqual(fresh.parameters);
    for (const c of fresh.cases) {
      const s = saved.cases.find((x: { name: string }) => x.name === c.name);
      expect(s, c.name).toBeTruthy();
      expect(s.expected).toHaveLength(c.expected.length);
      c.expected.forEach((step, i) => {
        const e = s.expected[i];
        expect(step.at_offset_ms, `${c.name}[${i}].at`).toBe(e.at_offset_ms);
        expect(step.interval_ms, `${c.name}[${i}].interval`).toBe(e.interval_ms);
        expect(step.stability).toBeCloseTo(e.stability, 6);
        expect(step.difficulty).toBeCloseTo(e.difficulty, 6);
        expect(step.state).toBe(e.state);
        expect(step.reps).toBe(e.reps);
        expect(step.lapses).toBe(e.lapses);
      });
    }
  });
});
